package org.mjdev.desktop.helpers.font.guard

/**
 * Builds the fontconfig file that hides the broken fonts. It rejects every file by its full path
 * (short globs like `*.woff2` are silently ignored by fontconfig 2.15) and then includes the
 * normal configuration, so every other font and user setting stays as it was.
 */
object FontGuardConfig {
    /** XML characters that must be escaped, with their entities. */
    private val XML_ESCAPES =
        listOf(
            "&" to "&amp;",
            "<" to "&lt;",
            ">" to "&gt;",
            "\"" to "&quot;",
            "'" to "&apos;",
        )

    /** Configuration including [baseConfig] and rejecting every file of [rejectedFiles]. */
    fun render(
        baseConfig: String,
        rejectedFiles: List<String>,
    ): String = buildString {
        appendLine("<?xml version=\"1.0\"?>")
        appendLine("<!DOCTYPE fontconfig SYSTEM \"urn:fontconfig:fonts.dtd\">")
        appendLine("<!-- generated by mjdev-desktop font guard: fonts without a family freeze Skia -->")
        appendLine("<fontconfig>")
        appendLine("  <selectfont>")
        appendLine("    <rejectfont>")
        rejectedFiles.forEach { file -> appendLine("      <glob>${file.escapeXml()}</glob>") }
        appendLine("    </rejectfont>")
        appendLine("  </selectfont>")
        appendLine("  <include ignore_missing=\"no\">${baseConfig.escapeXml()}</include>")
        appendLine("</fontconfig>")
    }

    private fun String.escapeXml(): String = XML_ESCAPES.fold(this) { text, (raw, entity) -> text.replace(raw, entity) }
}
