package org.mjdev.desktop.managers.theme.linux.gtk

import java.io.File

/** Builds the text of a generated GTK3 / GTK4 stylesheet. */
object GtkCss {
    /** Header marking the file as generated (it is rewritten on every palette change). */
    private const val HEADER = "/* Generated by mjdev-desktop from the wallpaper palette - do not edit. */"

    /** Blank line between sections. */
    private const val SECTION_SEPARATOR = "\n\n"

    /**
     * Stylesheet for [toolkit] in [layer].
     *
     * @param compositorDrawsFrame add [CompositorChromeRules] (mjdev compositor session only)
     * @param themesDir system theme dir searched for the stock base theme
     */
    fun build(
        toolkit: GtkToolkit,
        layer: GtkCssLayer,
        colors: GtkThemeColors,
        compositorDrawsFrame: Boolean,
        themesDir: File = GtkBaseTheme.SYSTEM_THEMES_DIR,
    ): String = buildList {
        add(HEADER)
        if (layer == GtkCssLayer.THEME) {
            add("@import url(\"${GtkBaseTheme.importUrl(toolkit, colors.isDark, themesDir)}\");")
        }
        add(GtkNamedColor.entries.joinToString("\n") { named -> named.define(colors) })
        if (layer == GtkCssLayer.THEME) {
            add(GtkWidgetRules.CSS)
        }
        if (compositorDrawsFrame) {
            add(CompositorChromeRules.CSS)
        }
    }.joinToString(SECTION_SEPARATOR) + "\n"
}
