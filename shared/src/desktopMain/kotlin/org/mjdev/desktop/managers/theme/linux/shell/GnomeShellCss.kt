package org.mjdev.desktop.managers.theme.linux.shell

import org.mjdev.desktop.managers.theme.linux.gtk.CssColor.css
import org.mjdev.desktop.managers.theme.linux.gtk.GtkThemeColors

/**
 * Builds `~/.themes/Mjdev/gnome-shell/gnome-shell.css` (loaded by the User Themes extension):
 * the stock Yaru / Adwaita shell stylesheet + palette colors for panel, menus, quick settings,
 * calendar / notifications, dash, switchers, OSDs and dialogs. Geometry stays stock.
 */
object GnomeShellCss {
    /** Theme sub directory. */
    const val DIR_NAME = "gnome-shell"

    /** Stylesheet file name the User Themes extension looks for. */
    const val FILE_NAME = "gnome-shell.css"

    /** Panel opacity, keeps the stock slightly translucent top bar. */
    private const val PANEL_ALPHA = 0.92f

    /** Dash background opacity. */
    private const val DASH_ALPHA = 0.85f

    /** Stylesheet for [colors] on [base]. */
    fun build(
        colors: GtkThemeColors,
        base: GnomeShellBase,
    ): String {
        val bg = css(colors.windowBg)
        val fg = css(colors.windowFg)
        val popover = css(colors.popoverBg)
        val card = css(colors.cardBg)
        val hover = css(colors.buttonHoverBg)
        val button = css(colors.buttonBg)
        val border = css(colors.border)
        val accent = css(colors.accentBg)
        val accentFg = css(colors.accentFg)
        return """
            /* Generated by mjdev-desktop from the wallpaper palette - do not edit. */
            @import url("${base.stylesheet(colors.isDark)}");

            #panel {
                background-color: ${css(colors.windowBg, PANEL_ALPHA)};
            }

            #panel .panel-button, #panel .clock {
                color: $fg;
            }

            .popup-menu-content, .candidate-popup-content, .quick-settings, .datemenu-popover,
            .switcher-list, .osd-window, .resize-popup, .modal-dialog, .end-session-dialog,
            .prompt-dialog, .run-dialog, .workspace-switcher {
                background-color: $popover;
                color: $fg;
                border-color: $border;
            }

            .popup-menu-item:hover, .popup-menu-item:focus, .popup-sub-menu .popup-menu-item:hover,
            .switcher-list .item-box:hover, .modal-dialog-button-box .button:hover {
                background-color: $hover;
                color: $fg;
            }

            .popup-sub-menu, .quick-toggle, .quick-menu-toggle .quick-toggle-arrow, .icon-button,
            .modal-dialog-button-box .button, .message-list-clear-button {
                background-color: $button;
                color: $fg;
            }

            .quick-toggle:checked, .quick-menu-toggle .quick-toggle:checked,
            .quick-menu-toggle .quick-toggle-arrow:checked, .switcher-list .item-box:selected,
            .popup-menu-item:checked, .calendar-today, .calendar-today:selected {
                background-color: $accent;
                color: $accentFg;
            }

            .message, .notification-banner, .events-button, .world-clocks-button, .weather-button,
            .message-media-control, .media-message {
                background-color: $card;
                color: $fg;
            }

            .dash-background {
                background-color: ${css(colors.windowBg, DASH_ALPHA)};
            }

            .search-entry, .login-dialog-prompt-entry, StEntry {
                background-color: $button;
                color: $fg;
            }

            .search-entry:focus, StEntry:focus {
                border-color: $accent;
            }

            .slider {
                -barlevel-active-background-color: $accent;
                -barlevel-background-color: $border;
            }

            .level-bar, .osd-window .level {
                -barlevel-active-background-color: $accent;
            }

            .button.default, .modal-dialog-button-box .button.default {
                background-color: $accent;
                color: $accentFg;
            }

            #overviewGroup, .workspace-background {
                background-color: $bg;
            }
            """.trimIndent() + "\n"
    }
}
