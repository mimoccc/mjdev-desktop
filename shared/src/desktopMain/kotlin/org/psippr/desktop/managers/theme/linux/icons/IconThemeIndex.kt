package org.psippr.desktop.managers.theme.linux.icons

/**
 * Builds the `index.theme` of a generated icon theme: every size and context folder, and the
 * theme it inherits icons it lacks from.
 */
object IconThemeIndex {
    /** File name of the index. */
    const val FILE_NAME = "index.theme"

    /** Key marking a theme made by this generator, with its version. */
    const val GENERATOR_KEY = "X-Psippr-Generator"

    /** Generator version; a theme with another one is made again. */
    const val GENERATOR_VERSION = 1

    /** Last resort theme every icon theme may inherit. */
    const val HICOLOR = "hicolor"

    /** Index of the theme [name] made from the font [fontName], inheriting [inherits]. */
    fun build(
        name: String,
        fontName: String,
        inherits: String,
    ): String {
        val dirs = IconSize.entries.flatMap { size -> IconContext.entries.map { context -> size to context } }
        return buildString {
            appendLine("[Icon Theme]")
            appendLine("Name=$name")
            appendLine("Comment=Icons generated by psippr-desktop from the $fontName icon font")
            appendLine("Inherits=${listOf(inherits, HICOLOR).distinct().joinToString(",")}")
            appendLine("Directories=${dirs.joinToString(",") { (size, context) -> dirOf(size, context) }}")
            appendLine("$GENERATOR_KEY=$GENERATOR_VERSION")
            dirs.forEach { (size, context) ->
                appendLine()
                appendLine("[${dirOf(size, context)}]")
                appendLine("Size=${size.px}")
                appendLine("Context=${context.title}")
                appendLine("Type=Fixed")
            }
        }
    }

    /** True when [index] was made by this generator version. */
    fun isCurrent(index: String): Boolean = index.lineSequence().any { line ->
        line.trim() ==
            "$GENERATOR_KEY=$GENERATOR_VERSION"
    }

    /** Folder of [size] and [context] (`48x48/places`). */
    fun dirOf(
        size: IconSize,
        context: IconContext,
    ): String = "${size.dirName}/${context.dirName}"
}
