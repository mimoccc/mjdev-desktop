package org.psippr.desktop.managers.theme.linux.gtk

import java.io.File

/**
 * Builds `~/.themes/Psippr/gtk-2.0/gtkrc`: palette colors + the stock Adwaita GTK2 widget rc files
 * (GTK2 resolves symbolic colors while parsing, so the scheme must come before the includes).
 */
object Gtk2Rc {
    /** Directory of the light stock GTK2 theme. */
    private const val LIGHT_DIR = "Adwaita/gtk-2.0"

    /** Directory of the dark stock GTK2 theme. */
    private const val DARK_DIR = "Adwaita-dark/gtk-2.0"

    /** Stock rc files with the widget styles, in include order. */
    private val INCLUDES = listOf("main.rc", "apps.rc", "hacks.rc")

    /** Extra rc file of the dark stock theme, included when present. */
    private const val DARK_HACKS = "hacks-dark.rc"

    /** Name of the GTK2 theme file. */
    const val FILE_NAME = "gtkrc"

    /** Theme sub directory. */
    const val DIR_NAME = "gtk-2.0"

    /** rc text for [colors]. */
    fun build(
        colors: GtkThemeColors,
        themesDir: File = GtkBaseTheme.SYSTEM_THEMES_DIR,
    ): String {
        val baseDir =
            File(themesDir, if (colors.isDark) DARK_DIR else LIGHT_DIR)
                .takeIf { dir -> dir.isDirectory } ?: File(themesDir, LIGHT_DIR)
        val scheme = Gtk2SchemeColor.entries.joinToString("\\n") { color -> color.entry(colors) }
        val includes =
            (INCLUDES + DARK_HACKS)
                .map { rc -> File(baseDir, rc) }
                .filter { rc -> rc.name != DARK_HACKS || rc.isFile }
                .joinToString("\n") { rc -> "include \"${rc.absolutePath}\"" }
        return "# Generated by psippr-desktop from the wallpaper palette - do not edit.\n" +
            "gtk-color-scheme = \"$scheme\"\n" +
            "gtk-auto-mnemonics = 1\n" +
            "gtk-primary-button-warps-slider = 1\n" +
            includes + "\n"
    }
}
